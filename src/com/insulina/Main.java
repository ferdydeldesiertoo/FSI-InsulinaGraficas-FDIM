    private void buttonPromedioMensualActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonPromedioMensualActionPerformed
        String query = "SELECT CONCAT(año, '-', mes) AS periodo, glucosa_prom FROM promedios_mensuales WHERE curp = '" + (String) comboBoxCurp.getSelectedItem() + "'";
        String queryTabla = "SELECT * FROM promedios_mensuales WHERE curp = '" + (String) comboBoxCurp.getSelectedItem() + "'";

        datos.clear();
        series.clear();

        datos = cnx.consultar(query);
        series.add("Promedio mensual");

        panelGrafica.removeAll();
        chart = new GraficaXY("Promedio Mensual de Glucosa", "Mes", "Nivel Promedio", series, datos);
        panelGrafica.add(chart.chartPanel);
        panelGrafica.updateUI();

        cnx.entablar(queryTabla, tableQuery);
    }//GEN-LAST:event_buttonPromedioMensualActionPerformed

    private void buttonPromedioPacienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonPromedioPacienteActionPerformed
        String queryGrafica = "SELECT nombrep, glucosa_prom FROM promedios";
        String queryTabla = "SELECT * FROM promedios";

        datos.clear();
        series.clear();

        datos = cnx.consultar(queryGrafica);
        series.add("Glucosa Promedio General");

        panelGrafica.removeAll();
        panelGrafica.setLayout(new java.awt.BorderLayout());
        chart = new GraficaXY("Promedio General de Glucosa por Paciente",
                "Paciente", "Nivel Promedio", series, datos);
        panelGrafica.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
        panelGrafica.revalidate();
        panelGrafica.repaint();

        cnx.entablar(queryTabla, tableQuery);
    }//GEN-LAST:event_buttonPromedioPacienteActionPerformed

    private void buttonMedicionesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonMedicionesActionPerformed
        String query = "SELECT nombrep, COUNT(*) AS total_mediciones "
                + "FROM mediciones, pacientes "
                + "WHERE curp = pacientes_curp "
                + "GROUP BY curp";

        datos.clear();
        series.clear();

        datos = cnx.consultar(query);
        series.add("Mediciones Registradas");

        panelGrafica.removeAll();
        panelGrafica.setLayout(new java.awt.BorderLayout());
        chart = new GraficaXY("Cantidad de Mediciones por Paciente",
                "Paciente", "Total de Registros", series, datos);
        panelGrafica.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
        panelGrafica.revalidate();
        panelGrafica.repaint();

        cnx.entablar(query, tableQuery);
    }//GEN-LAST:event_buttonMedicionesActionPerformed

